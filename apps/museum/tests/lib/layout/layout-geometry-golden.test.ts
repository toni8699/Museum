function sample6(sample: CompiledCurveSample): [number, number, number, number, number, number] {
	return [sample.point[0], sample.point[1], sample.distance, sample.t, sample.tangent[0], sample.tangent[1]];
}

/** Full per-sample golden — locks sampling, arc length, tangents, sections, polygons, and bounds. */
function fullRoomProjection(geometry: CompiledLayoutGeometry) {
	return {
		rooms: geometry.rooms.map((room) => ({
			roomId: room.roomId,
			floorElevation: room.floorElevation,
			ceilingElevation: room.ceilingElevation,
			floorPolygon: room.floorPolygon,
			bounds3: room.bounds3,
			walls: room.walls.map((wall) => ({
				segmentId: wall.segmentId,
				length: wall.length,
				samples: wall.samples.map(sample6),
				sections: wall.sections.map((section) => [
					section.kind,
					section.startDistance,
					section.endDistance,
					section.bottomY,
					section.topY,
					section.openingId ?? null,
					section.profile?.kind ?? null,
					section.profile?.topBoundary ?? null
				]),
				openings: wall.openings.map((opening) => [
					opening.openingId,
					opening.kind,
					opening.offset,
					opening.width,
					opening.height,
					opening.sillHeight,
					opening.profile,
					opening.center.point,
					opening.center.yaw
				])
			}))
		})),
		objects: geometry.objects.map((object) => ({
			objectId: object.objectId,
			kind: object.kind,
			worldAabb: object.worldAabb,
			planFootprint: object.planFootprint
		})),
		bounds: geometry.bounds
	};
}

/** Compact golden — spot samples + lengths + section/profile summaries, enough to catch drift. */
function digestProjection(geometry: CompiledLayoutGeometry) {
	return {
		rooms: geometry.rooms.map((room) => ({
			roomId: room.roomId,
			floorElevation: room.floorElevation,
			ceilingElevation: room.ceilingElevation,
			floorPolygon: room.floorPolygon,
			bounds3: room.bounds3,
			walls: room.walls.map((wall) => ({
				segmentId: wall.segmentId,
				length: wall.length,
				sampleCount: wall.samples.length,
				firstSample: sample6(wall.samples[0]!),
				midSample: sample6(wall.samples[Math.floor(wall.samples.length / 2)]!),
				lastSample: sample6(wall.samples.at(-1)!),
				sections: wall.sections.map((section) => [
					section.kind,
					section.startDistance,
					section.endDistance,
					section.bottomY,
					section.topY,
					section.openingId ?? null,
					section.profile?.kind ?? null,
					section.profile?.topBoundary ?? null
				])
			}))
		})),
		objects: geometry.objects.map((object) => ({
			objectId: object.objectId,
			kind: object.kind,
			worldAabb: object.worldAabb,
			planFootprint: object.planFootprint
		})),
		bounds: geometry.bounds
	};
}

